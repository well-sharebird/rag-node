type TranslationKey = keyof typeof translations.en;
type DynamicTranslationKey = `section.${string}` | `nav.${string}` | `dataSource.sourceType.${string}` | `model.type.${string}` | `model.adapter.${string}`;

interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: TranslationKey | DynamicTranslationKey) => string;
  toast: {
    success: (message: string) => void;
    error: (message: string) => void;
    info: (message: string) => void;
    confirm: (message: string) => Promise<boolean>;
  };
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('zh'); // Default to Chinese

  const t = (key: TranslationKey | DynamicTranslationKey) => {
    return translations[language][key as TranslationKey] || translations.en[key as TranslationKey] || key;
  };

  const toastUtils = {
    success: (message: string) => {
      sonnerToast.success(t('toast.success'), { description: message });
    },
    error: (message: string) => {
      sonnerToast.error(t('toast.error'), { description: message });
    },
    info: (message: string) => {
      sonnerToast.info(message);
    },
    confirm: (message: string) => {
      return new Promise<boolean>((resolve) => {
        resolve(window.confirm(message));
      });
    },
  };

  const contextValue = { language, setLanguage, t, toast: toastUtils };
  return (
    <I18nContext.Provider value={contextValue as unknown as I18nContextType}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (context === undefined) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
}
